class I18n:
    def __init__(self, lang="en"):
        self.lang = lang if lang in STRINGS else "en"

    def __call__(self, _key, /, **kw):  # positional-only: placeholder boleh bernama "key"
        s = STRINGS[self.lang].get(_key) or STRINGS["en"].get(_key) or _key
        return s.format(**kw) if kw else s


T = I18n("en")  # instance bersama untuk engine, CLI, dan GUI


def fmt_date(value, seconds: bool = False) -> str:
    """Tanggal sesuai bahasa aktif, mis. '29 Oct 2026 09:15' / '29 Okt 2026 09:15'."""
    from datetime import datetime
    d = value if isinstance(value, datetime) else datetime.fromtimestamp(value)
    month = MONTHS.get(T.lang, MONTHS["en"])[d.month - 1]
    return f"{d.day:02d} {month} {d.year} {d:%H:%M:%S}" if seconds else f"{d.day:02d} {month} {d.year} {d:%H:%M}"


def fmt_duration(secs: float) -> str:
    """Durasi ringkas: '45 s', '3:05', '1:02:09'."""
    secs = max(0, int(round(secs)))
    if secs < 60:
        return f"{secs} s"
    h, rem = divmod(secs, 3600)
    m, s = divmod(rem, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"
